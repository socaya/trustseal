"""Read-only, document-authorized legacy activity history.

Activity records are written by trusted domain services, never supplied
directly by clients through arbitrary CRUD.
"""
from flask import Blueprint, abort, jsonify, request
from flask_jwt_extended import jwt_required
from app.models.documents.document_activity import DocumentActivity
from app.blueprints.documents.api.document_api import get_authorized_document_or_abort

document_activity_api = Blueprint("document_activity_api", __name__, url_prefix="/api/document-activity")


def _serialize(item):
    return {
        "id": item.id, "document_id": item.document_id,
        "activity_type": item.activity_type, "details": item.details,
        "user_id": item.user_id,
        "created_at": item.created_at.isoformat() if item.created_at else None,
    }


@document_activity_api.route("/", methods=["GET"])
@jwt_required()
def list_document_activities():
    raw = request.args.get("document_id")
    if raw is None or not raw.isdecimal():
        abort(400, description="document_id query parameter required")
    document_id = int(raw)
    get_authorized_document_or_abort(document_id)
    items = DocumentActivity.query.filter_by(document_id=document_id).order_by(
        DocumentActivity.created_at.desc()
    ).limit(100).all()
    return jsonify([_serialize(item) for item in items])


@document_activity_api.route("/<int:item_id>", methods=["GET"])
@jwt_required()
def get_document_activity(item_id):
    item = DocumentActivity.query.get_or_404(item_id)
    get_authorized_document_or_abort(item.document_id)
    return jsonify(_serialize(item))


@document_activity_api.route("/", methods=["POST"])
@document_activity_api.route("/<int:item_id>", methods=["PUT", "PATCH", "DELETE"])
@jwt_required()
def reject_client_activity_mutation(item_id=None):
    abort(409, description="Document activities are generated by audited services")
